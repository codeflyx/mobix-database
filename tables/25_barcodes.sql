-- ============================================================
-- TABLE: barcodes
-- Purpose: MANY codes pointing at ONE target. Every scan in the app
--   resolves through this single table (see lib/scan.js).
--
-- THE MODEL — easy to get backwards:
--   A barcode identifies a KIND, not a THING.
--   100 identical back covers share ONE code. Scanning it means
--   "+1 to the cart"; stock is a count. They are fungible — nobody
--   will ever care whether cover #47 or #48 was sold, and giving
--   each one a unique code multiplies every receive, stock-take and
--   return by 100 for no benefit.
--
--   A variant holds SEVERAL codes because the SAME item arrives with
--   supplier A's barcode this month, supplier B's next month, plus
--   the shop's own printed label. Three ALIASES, one variant —
--   not three units.
--
--   Serialised goods invert this: kind='unit' points one code at one
--   imei_units row, because a phone with a warranty and an IMEI is
--   not interchangeable with the next one.
--
-- kind / target — exactly one of these is set:
--   'variant' → variant_id → product_variants (add 1 to the line)
--   'unit'    → unit_id    → imei_units       (add THAT unit)
--
-- source: where the code came from —
--   'supplier' printed on the item by its manufacturer
--   'printed'  generated by this shop (see item_labels / lib/labels.js)
--   'imported' migrated from the old products.barcode column
--   'manual'   typed in by hand
--
-- barcodes_owner_code_uq is the load-bearing index: a code MUST
--   resolve to exactly one target per shop or scanning is ambiguous.
--   addBarcode() in lib/variants.js checks it first and returns a
--   readable "already used by X" error instead of a UNIQUE violation.
--
-- No soft delete — a detached barcode is just gone (hard delete is
--   safe; historical sales reference variant_id, never the code).
--
-- Created by migrations/migrate_14_variants_barcodes.sql, applied
-- automatically by lib/variants.js ensureVariantsSchema().
-- ============================================================

CREATE TABLE IF NOT EXISTS barcodes (
  id            TEXT PRIMARY KEY NOT NULL,
  owner_user_id TEXT NOT NULL REFERENCES users (id),

  code          TEXT NOT NULL,
  kind          TEXT NOT NULL DEFAULT 'variant' CHECK (kind IN ('variant','unit')),

  variant_id    TEXT REFERENCES product_variants (id),
  unit_id       TEXT REFERENCES imei_units (id),

  source        TEXT NOT NULL DEFAULT 'manual'
                CHECK (source IN ('manual','supplier','printed','imported')),

  created_at    TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%SZ','now'))
);

CREATE UNIQUE INDEX IF NOT EXISTS barcodes_owner_code_uq
  ON barcodes (owner_user_id, code);

CREATE INDEX IF NOT EXISTS barcodes_variant_idx ON barcodes (variant_id);
CREATE INDEX IF NOT EXISTS barcodes_unit_idx    ON barcodes (unit_id);
